def troca(t, ini_pat, fim_pat, novo, incluir_fim=True):
    a = re.search(ini_pat, t)
    b = re.search(fim_pat, t[a.start():]) if a else None
    if not (a and b):
        raise SystemExit(f"marcadores não encontrados: {ini_pat} .. {fim_pat}")
    fim = a.start() + (b.end() if incluir_fim else b.start())
    return t[:a.start()] + novo + t[fim:]


